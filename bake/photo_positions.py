"""Add the comet's position to each measured photo (web/data/comets/*/comet.json) and write the migration that adds it
to the database, so a comet's page can open the time-lapse on any of its photos, centred on the comet.

Photos baked before bake/comet_spectrum.py stored ra, dec per photo carry only file and mjd. The position is JPL
Horizons' as SPHEREx saw it at the photo's moment (comet_spectrum.horizons_at, the query the bake cuts photos out with;
checked 2026-11-17 against the 49 photos the bake's cache still measures: 35 within 0.1 arcsec, 3I/ATLAS within 2.5
(its cutouts are centred on IRSA's positions), 8.2 on one 210P photo and 14 to 17.5 on C/2025 R2's three Oct 2025 photos,
not traced; a SPHEREx pixel is 6.15 arcsec).
Run: uv run -q --with astropy --with pillow --with certifi --with reproject sh -c 'SSL_CERT_FILE=$(python -m certifi) exec python bake/photo_positions.py 0016_photo_positions'
"""
import json, sys

from comet_spectrum import ROOT, horizons_at
from seed_d1 import q

CACHE_NAME = {"3I/ATLAS": "C/2025 N1 (ATLAS)"}   # 3I/ATLAS's name in bake/cache/known_comets.json
pdes = {k["name"]: k["pdes"] for k in json.loads((ROOT / "bake/cache/known_comets.json").read_text())}
sql = ["-- Generated by bake/photo_positions.py: the comet's position (ra, dec) on each measured photo"]
for f in sorted((ROOT / "web/data/comets").glob("*/comet.json")):
    c = json.loads(f.read_text())
    for p, (ra, dec) in zip(c["photos"], horizons_at(pdes[CACHE_NAME.get(c["id"], c["id"])], [p["mjd"] for p in c["photos"]])):
        p["ra"], p["dec"] = round(ra, 5), round(dec, 5)
    f.write_text(json.dumps(c, indent=1))
    photos = json.dumps(c["photos"], separators=(",", ":"))
    sql.append(f"UPDATE comets SET detail = json_set(detail, '$.photos', json({q(photos)})) WHERE id = {q(c['id'])};")
    print(f"{c['id']}: {len(c['photos'])} photos")
(ROOT / f"worker/migrations/{sys.argv[1]}.sql").write_text("\n".join(sql) + "\n")
