"""Write worker/migrations/0002_seed.sql: the comets the map starts with.

- 3I/ATLAS: real, with the measurements from bake/comet_3iatlas.py (web/data/comets/3i-atlas/comet.json).
- C-0147 and friends: example comets with example tagged comments, so tallies come from real rows of the
  comments table the same way they will for real comments. Marked real = 0; the page says "example".
Run: python3 bake/seed_d1.py   (then: npx wrangler d1 migrations apply comet-hunt --local/--remote)
After re-measuring 3I/ATLAS on a database that already has it, never edit an applied migration; write a new one:
     python3 bake/seed_d1.py --update 0003_atlas_flag_mask   (an UPDATE of its detail from comet.json)
Real known comets (bake/known_comets.py -> bake/cache/known_comets.json):
     python3 bake/seed_d1.py --known 0006_known_comets_refresh   (always a new number; 0005 added the track column)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
T0 = 1763000000000   # unix ms, 2025-11-13; example comments are spaced back from here

# id, ra, dec, day first seen, tail angle, tags {comet, asteroid, glitch, unsure}
EXAMPLE = [
    ("C-0147", 328, 34, 127, -150, dict(comet=12, asteroid=1, unsure=1)),
    ("C-0152", 18, 22, 160, -35, dict(comet=6, asteroid=1)),
    ("C-0161", 300, -30, 210, -120, dict(comet=2, asteroid=1, unsure=1)),
    ("C-0170", 95, -12, 245, -200, dict(comet=5)),
    ("C-0174", 140, 48, 330, -60, dict(comet=1, glitch=1, unsure=1)),
]
KNOWN = [(60, 21), (122, 17), (171, 4), (282, -24), (346, -7), (35, -38)]   # example catalog markers
# the conversation shown on C-0147's page (from design/screens/comet.html); other votes have no text
TALK = [("orbit_owl", "comet", "The tail points away from the Sun in all six photos."),
        ("kepler_kid", "comet", "Checked the catalogs. Nothing at this spot."),
        ("dustlane", "asteroid", "The February photos look sharp to me."),
        ("mira_v", "unsure", "Not sure yet, the first two photos are noisy."),
        ("mira_v", "comet", "Strong carbon dioxide peak at 4.26."),
        ("nightshift_nel", None, "Does anyone have the March photos yet?")]


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    rows, comments = [], []
    atlas = json.loads((ROOT / "web/data/comets/3i-atlas/comet.json").read_text())
    rows.append(("3I/ATLAS", "known", atlas["ra"], atlas["dec"], int(atlas["first_mjd"] - 60789), None, 1, json.dumps(atlas, separators=(",", ":"))))
    for i, (ra, dec) in enumerate(KNOWN, 1):
        rows.append((f"known-{i}", "known", ra, dec, 0, None, 0, None))
    for cid, ra, dec, day, tail, tags in EXAMPLE:
        rows.append((cid, "comet", ra, dec, day, tail, 0, None))
        talk = TALK if cid == "C-0147" else []
        named = {}
        for a, tag, body in talk:
            if tag: named[a] = tag   # latest tag per person counts
        left = dict(tags)
        for tag in named.values():
            left[tag] -= 1
        n = 0
        for tag, count in left.items():
            for _ in range(count):
                n += 1
                comments.append((cid, f"hunter_{cid[-3:]}_{n}", tag, "", T0 - (len(comments) + 50) * 600000))
        for k, (a, tag, body) in enumerate(talk):
            comments.append((cid, a, tag, body, T0 - (len(talk) - k) * 1200000))
    sql = ["-- Generated by bake/seed_d1.py. Example rows have real = 0; 3I/ATLAS is real SPHEREx data."]
    for r in rows:
        sql.append("INSERT INTO comets (id, kind, ra, dec, day, tail, real, detail) VALUES (" + ", ".join(q(v) for v in r) + ");")
    for c in comments:
        sql.append("INSERT INTO comments (comet_id, author, tag, body, created_at) VALUES (" + ", ".join(q(v) for v in c) + ");")
    out = ROOT / "worker/migrations/0002_seed.sql"
    out.write_text("\n".join(sql) + "\n")
    print(f"wrote {out.name}: {len(rows)} comets, {len(comments)} comments, {out.stat().st_size // 1024} KB")


def update(name):
    atlas = json.loads((ROOT / "web/data/comets/3i-atlas/comet.json").read_text())
    out = ROOT / f"worker/migrations/{name}.sql"
    out.write_text("-- Generated by bake/seed_d1.py --update: 3I/ATLAS re-measured by bake/comet_3iatlas.py\n"
                   f"UPDATE comets SET ra = {atlas['ra']}, dec = {atlas['dec']}, detail = {q(json.dumps(atlas, separators=(',', ':')))} WHERE id = '3I/ATLAS';\n")
    print(f"wrote {out.name}")


def known(name):
    comets = json.loads((ROOT / "bake/cache/known_comets.json").read_text())
    # A refresh, safe on any database that already has the track column (0005 added it): it replaces every known
    # comet except 3I/ATLAS, whose measured record is kept. Each re-bake gets a NEW numbered migration, because a
    # database that applied an earlier file skips it even if the file is rewritten.
    sql = ["-- Generated by bake/seed_d1.py --known: real comets from JPL (SBDB + Horizons) matched to SPHEREx photos.",
           "-- track: [[day, ra, dec, magnitude], ...] every 10 days since 2025-04-24, for the map's moving markers.",
           "DELETE FROM comets WHERE kind = 'known' AND id != '3I/ATLAS' AND id NOT IN (SELECT comet_id FROM comments);"]
    for c in comets:
        last = c["track"][-1][0]   # keep the final point too, so markers move through the last days of coverage
        track = [[d, r, dc, None if m is None else round(m, 1)] for d, r, dc, m in c["track"] if d % 10 == 0 or d == last]
        if "2025 N1" in c["pdes"]:   # 3I/ATLAS already has its measured record; give it a path so it moves too
            sql.append(f"UPDATE comets SET track = {q(json.dumps(track, separators=(',', ':')))} WHERE id = '3I/ATLAS';")
            continue
        mid = c["track"][len(c["track"]) // 2]
        detail = dict(name=c["name"], q=c["q"], tp=c["tp"], spherex=c["spherex"],
                      mags=[[d, m] for d, _, _, m in c["track"] if m is not None and (d % 10 == 0 or d == last)])
        # upsert, never delete-and-insert: a known comet may already have comments pointing at it
        sql.append("INSERT INTO comets (id, kind, ra, dec, day, tail, real, detail, track) VALUES (" + ", ".join(
            q(v) for v in (c["name"], "known", mid[1], mid[2], 0, None, 1, json.dumps(detail, separators=(",", ":")),
                           json.dumps(track, separators=(",", ":")))) + ") ON CONFLICT(id) DO UPDATE SET ra = excluded.ra, "
                   "dec = excluded.dec, real = excluded.real, detail = excluded.detail, track = excluded.track;")
    out = ROOT / f"worker/migrations/{name}.sql"
    out.write_text("\n".join(sql) + "\n")
    print(f"wrote {out.name}: {len(comets)} comets, {out.stat().st_size // 1024} KB")


if __name__ == "__main__":
    import sys
    if "--update" in sys.argv: update(sys.argv[2])
    elif "--known" in sys.argv: known(sys.argv[2])
    else: main()
